"""Verify the static-only (file://) mode of the site with Playwright.

Usage: python scripts/check_offline.py

Checks that opening site/index.html directly gives a working offline demo:
banner, scanner, pricing checkout, console ledger and integrations.
"""

from __future__ import annotations

import sys
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent
SITE = (ROOT / "site" / "index.html").as_uri()
failures: list[str] = []


def expect(condition: bool, message: str) -> None:
    if not condition:
        failures.append(message)
        print("FAIL:", message)
    else:
        print("ok  :", message)


def main() -> int:
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport={"width": 1440, "height": 1000})
        page.on("pageerror", lambda exc: failures.append(f"pageerror: {exc}"))

        page.goto(SITE + "#/home", wait_until="load")
        page.wait_for_timeout(800)
        expect(page.locator("#offlineBanner").is_visible(), "offline banner is visible")
        expect(page.locator("#scanPlaceholder").is_visible(), "scanner placeholder shown")

        page.click("[data-sample='danger']")
        page.click("#scanBtn")
        page.wait_for_selector("#scanResult:not([hidden])", timeout=15000)
        page.wait_for_timeout(600)
        grade = page.locator("#gradeLetter").inner_text()
        expect(grade == "F", f"offline scanner grades dangerous config F (got {grade})")
        policy = page.locator("#policyPreview").inner_text()
        expect("deny-default" in policy, "offline scanner renders deny-default policy")
        expect("Generated by AgentProof.cloud scanner" in policy, "policy has scanner header")

        page.goto(SITE + "#/pricing", wait_until="load")
        page.wait_for_timeout(500)
        page.fill("#companyInput", "Offline Demo Co")
        page.fill("#emailInput", "demo@offline.dev")
        page.select_option("#planSelect", "pro")
        page.click("#signupBtn")
        page.wait_for_selector("#signupSuccess:not([hidden])", timeout=15000)
        key = page.locator("#newApiKey").inner_text()
        expect(key.startswith("ap_"), f"offline signup issues a key (got {key[:10]}…)")

        page.goto(SITE + "#/console", wait_until="load")
        page.wait_for_selector("#consoleRoot:not([hidden])", timeout=15000)
        page.wait_for_timeout(800)
        mode = page.locator("#dataModeTag").inner_text()
        expect(mode == "DEMO", f"console shows DEMO mode (got {mode})")
        page.click("#simulateBtn")
        page.wait_for_timeout(900)
        rows = page.locator("#ledgerBody tr").count()
        expect(rows >= 2, f"offline ledger has records (got {rows})")
        page.click("#verifyBtn")
        page.wait_for_timeout(900)
        verdict = page.locator("#verifyVerdict").inner_text()
        expect(verdict.startswith("PASS"), f"offline verification passes (got {verdict})")

        page.goto(SITE + "#/integrations", wait_until="load")
        page.wait_for_timeout(500)
        page.click("[data-vendor='vanta']")
        page.wait_for_timeout(1000)
        payload = page.locator("#exportPreview").inner_text()
        expect("vanta.evidence_pack" in payload, "offline integrations build a Vanta draft")
        expect("draft" in payload, "offline export is marked as a draft")

        page.screenshot(path=str(ROOT / ".tmp" / "offline-console.png"))
        browser.close()

    print()
    if failures:
        print(f"{len(failures)} failure(s)")
        return 1
    print("offline mode OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
